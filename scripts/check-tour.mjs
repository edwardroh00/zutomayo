import assert from 'node:assert/strict';
import fs from 'node:fs';
import {emptyProfile,validateProfile,parseBackup,exportBackup,calculateStats,isRecordableEvent} from '../fan-model.js';
import {TOUR_ID,tourPage,tourCalendar} from '../tour-planner.js';
import {ko,bilingual} from '../korean.js';
const read=n=>JSON.parse(fs.readFileSync('data/'+n+'.json'));
const events=read('lives').events,songs=read('songs').songs,goods=read('goods').goods;
const tour=events.filter(e=>e.groupId===TOUR_ID);
const venues=read('tour-venues').venues;
assert.equal(venues.length,23);assert.equal(new Set(venues.map(v=>v.venue)).size,23);
assert(tour.every(e=>venues.some(v=>v.venue===e.venue&&v.city===e.city&&v.region===e.region)));
assert(venues.every(v=>v.lat>30&&v.lat<46&&v.lng>128&&v.lng<146&&v.source.startsWith('https://')));
assert(venues.find(v=>v.city==='나고야').lng>136.9);
assert(venues.find(v=>v.city==='오이타').lat>33.23);
assert.equal(ko('ZUTOMAYO'),'즛토마요');
assert(events.every(e=>!/[ぁ-鿿]/.test(ko(e.name))&&!/[ぁ-鿿]/.test(ko(e.venue))));
assert(bilingual('東京ガーデンシアター').startsWith('도쿄 가든 시어터'));
assert(bilingual('東京ガーデンシアター').includes('class="original-name"'));
assert.equal(tour.length,36);assert.equal(new Set(tour.map(e=>e.id)).size,36);
const evidence=JSON.parse(fs.readFileSync('project_memory/APICULA_2027_EVIDENCE.json'));
assert.equal(evidence.count,36);assert.deepEqual(evidence.differences,[]);
for(const e of tour){const official=evidence.rows.find(r=>r.date===e.date);assert(official);for(const key of ['venue','region','open','start'])assert.equal(e[key],official[key]);assert.equal(e.officialSource,evidence.source);assert.equal(e.metadataStatus,'official_checked');}
assert.equal(tour[0].date,'2027-01-15');assert.equal(tour.at(-1).date,'2027-05-23');
assert.deepEqual([1,2,3,4,5].map(m=>tour.filter(e=>Number(e.date.slice(5,7))===m).length),[6,6,9,7,8]);
assert(tour.every(e=>!isRecordableEvent(e)));
const old=emptyProfile();delete old.tourPlans;
assert.deepEqual(validateProfile(old,songs,events,goods).tourPlans,[]);
const p={...old,tourPlans:[{eventId:tour[0].id,ticketBooked:true}]};
assert.deepEqual(parseBackup(JSON.stringify(exportBackup(p)),songs,events,goods).tourPlans,p.tourPlans);
assert.equal(calculateStats(p,songs,events).attendances.length,0);
assert.equal(calculateStats(p,songs,events).heard.length,0);
assert.throws(()=>validateProfile({...p,tourPlans:[...p.tourPlans,...p.tourPlans]},songs,events,goods));
assert.throws(()=>validateProfile({...p,tourPlans:[{eventId:'invalid',ticketBooked:false}]},songs,events,goods));
assert.throws(()=>validateProfile({...p,attendances:[{id:tour[0].id+'@venue',eventId:tour[0].id,mode:'venue',coverage:'full',seat:'',memo:'',heardEntryIds:[]}]},songs,events,goods));
assert.equal((tourPage(events,p,{}).match(/class="tour-row/g)||[]).length,36);
assert.equal((tourPage(events,p,{tourMonth:'04'}).match(/class="tour-row/g)||[]).length,7);
assert.equal((tourPage(events,p,{tourChecked:true}).match(/class="tour-row/g)||[]).length,1);
const ics=tourCalendar(events,p.tourPlans);assert.equal((ics.match(/BEGIN:VEVENT/g)||[]).length,1);assert(ics.includes('DTSTART:20270115T090000Z'));assert(ics.split('\r\n').every(l=>Buffer.byteLength(l)<=75));
console.log('Tour checks passed: 36 schedules, 23 sourced map locations, filters, old profile migration, backup roundtrip, future attendance exclusion and JST calendar.');
